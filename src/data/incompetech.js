/**
 * Filter Incompetech tracks by search term
 */
export function searchIncompetechTracks(query = '') {
  const q = query.trim().toLowerCase()
  if (!q) return INCOMPETECH_TRACKS
  return INCOMPETECH_TRACKS.filter((track) => {
    return (
      track.title.toLowerCase().includes(q) ||
      track.genre.toLowerCase().includes(q) ||
      track.mood.toLowerCase().includes(q) ||
      track.tags.some((tag) => tag.toLowerCase().includes(q))
    )
  })
}
