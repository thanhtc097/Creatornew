/**
 * Filter Kenney tracks based on keyword and category
 */
export function searchKenneyTracks(query = '') {
  const q = query.trim().toLowerCase()
  if (!q) return KENNEY_TRACKS
  return KENNEY_TRACKS.filter((track) => {
    return (
      track.title.toLowerCase().includes(q) ||
      track.category.toLowerCase().includes(q) ||
      track.tags.some((tag) => tag.toLowerCase().includes(q))
    )
  })
}
