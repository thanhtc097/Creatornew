export function searchPixabayShowcase(query = '') {
  const q = query.trim().toLowerCase()
  if (!q) return PIXABAY_SHOWCASE
  return PIXABAY_SHOWCASE.filter((item) => {
    return (
      item.title.toLowerCase().includes(q) ||
      item.tags.some((tag) => tag.toLowerCase().includes(q))
    )
  })
}
