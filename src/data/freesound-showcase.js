export function searchFreesoundShowcase(query = '') {
  const q = query.trim().toLowerCase()
  if (!q) return FREESOUND_SHOWCASE
  return FREESOUND_SHOWCASE.filter((item) => {
    return (
      item.title.toLowerCase().includes(q) ||
      item.tags.some((tag) => tag.toLowerCase().includes(q))
    )
  })
}
