export function searchPexelsShowcase(query = '') {
  const q = query.trim().toLowerCase()
  if (!q) return PEXELS_SHOWCASE
  return PEXELS_SHOWCASE.filter((item) => {
    return (
      item.title.toLowerCase().includes(q) ||
      item.tags.some((tag) => tag.toLowerCase().includes(q))
    )
  })
}
